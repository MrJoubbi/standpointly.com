/**
 * Result URL parsing — §3.
 *
 * A result is fully described by two numbers and a config version, and all
 * three live in the query string. That makes every result shareable and
 * bookmarkable with no database (§2) — and it also means the values arrive
 * from an untrusted, hand-editable source, so nothing here trusts them.
 *
 * `v` is required. When questions get reworded the weights behind them move,
 * so a coordinate without a version cannot be attributed to any scoring run
 * and is treated as malformed rather than guessed at.
 */

import type { TestConfig } from "@/lib/types";

export type ParsedResult =
  | {
      ok: true;
      x: number;
      y: number;
      version: number;
      /** True when the link was generated by a different config version. */
      stale: boolean;
    }
  | { ok: false; reason: "missing" | "malformed" | "out_of_range" };

function coordinate(raw: string | undefined): number | null {
  if (raw === undefined || raw.trim() === "") return null;
  // Number() rather than parseFloat(): "0.4abc" must fail, not truncate.
  const value = Number(raw);
  return Number.isFinite(value) ? value : null;
}

export function parseResult(
  params: { x?: string; y?: string; v?: string },
  config: TestConfig,
): ParsedResult {
  if (
    params.x === undefined ||
    params.y === undefined ||
    params.v === undefined
  ) {
    return { ok: false, reason: "missing" };
  }

  const x = coordinate(params.x);
  const y = coordinate(params.y);
  const version = Number(params.v);

  if (x === null || y === null) return { ok: false, reason: "malformed" };
  if (!Number.isInteger(version) || version < 1) {
    return { ok: false, reason: "malformed" };
  }

  // Scoring clamps to ±clamp, so anything beyond it was not produced by this
  // engine. Refuse rather than silently pulling it back onto the grid.
  const limit = config.scoring.clamp;
  if (Math.abs(x) > limit || Math.abs(y) > limit) {
    return { ok: false, reason: "out_of_range" };
  }

  return { ok: true, x, y, version, stale: version !== config.version };
}
